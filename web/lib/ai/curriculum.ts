/** 학년 이름(중1, 공통수학1 …)에 맞는 안내를 찾는다. 모르는 이름이면 null */
export function findGuide(grade: string | undefined) {
  const g = (grade ?? "").replace(/\s+/g, " ").trim();
  if (!g) return null;
  return GUIDES.find((x) => x.match.test(g)) ?? null;
}

/** 프롬프트에 넣을 학년 범위 규칙. forProblem = 새 문제를 만드는 경우 (문제도 학년 범위 안에서) */
export function levelRules(level: Level = {}, forProblem = false) {
  const guide = findGuide(level.grade);
  const where = [level.grade, level.unit, level.type].map((s) => (s ?? "").trim()).filter(Boolean).join(" › ");
  const common = [
    "- 풀이와 해설은 이 학년 학생이 학교에서 이미 배운 개념·용어·기호·공식만 써서 작성하라. 이 학년 교과서와 같은 방식으로 풀어라.",
    "- 더 높은 학년(또는 교육과정 밖)의 공식·기호·정리를 쓰면 더 짧게 풀리더라도 쓰지 마라. 대신 이 학년 방식(직접 세기, 나열, 표, 그림, 식 세우기, 배운 성질)으로 풀어라.",
    "- 심화(난이도 상) 문제도 마찬가지다. 어려운 문제라도 이 학년에서 배운 것만으로 풀이를 써라.",
  ];
  if (forProblem) common.push("- 새로 만드는 문제도 이 학년 개념만으로 풀 수 있게 만들어라.");
  if (!guide) {
    return `
[학년 범위 (매우 중요)]
${where ? `- 이 문제의 분류: ${where}\n` : ""}- 문제의 단원과 수준을 보고 몇 학년 문제인지 먼저 판단한 뒤, 그 학년 교육과정(2022 개정) 범위 안에서만 풀이를 써라.
${common.join("\n")}
`;
  }
  return `
[학년 범위: ${guide.name} (매우 중요)]
- 이 문제의 분류: ${where}
${common.join("\n")}
- ${guide.name}까지 배우는 내용: 앞 학년 내용 + ${guide.learn}
- ${guide.name} 학생이 아직 배우지 않은 것 (풀이에 쓰지 마라): ${guide.avoid}${guide.tips ? `\n- 이 학년 방식으로 쓰는 요령: ${guide.tips}` : ""}
`;
}

/** 서버 액션에 들어온 분류 값을 정리한다 */
export function cleanLevel(v: unknown): Level {
  const o = (v && typeof v === "object" ? v : {}) as Record<string, unknown>;
  const s = (x: unknown) => (typeof x === "string" ? x.slice(0, 80) : "");
  return { grade: s(o.grade), unit: s(o.unit), type: s(o.type) };
}
